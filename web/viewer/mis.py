MAX_MA = BOUNDARIES_KA[-1][1] / 1000.0


def stage_ticks(max_ma: float) -> list[dict]:
    """그림 눈금 — `max_ma` 까지의 단계 경계를 (이름, Ma) 로 낸다.

    이름은 경계 표기(`5/6`)이고, 빙기/간빙기는 번호 짝홀로 화면이 가른다
    (짝수 빙기 · 홀수 간빙기 — 문자 단계 구간은 안 가른다)."""
    out = []
    for name, ka in BOUNDARIES_KA:
        ma = ka / 1000.0
        if ma > max_ma:
            break
        out.append({"boundary": name, "ma": ma})
    return out


def stage_of(age_ma: float) -> str:
    """연령(Ma) 이 어느 단계에 드는가 — **눈금 안내용**이다(위 머리말).
    LR04 범위 밖이면 빈 문자열."""
    if age_ma is None or age_ma < 0 or age_ma > MAX_MA:
        return ""
    prev = "1"
    for name, ka in BOUNDARIES_KA:
        if age_ma * 1000.0 <= ka:
            return prev
        prev = name.split("/")[1]
    return ""


def _stage_no(name: str) -> int:
    """`5` → 5 · `G2` → 2 · `KM3` → 3. 짝수가 빙기다 — 문자 단계도 같다
    (LR04 의 번호 규칙 · 짝수 = δ18O 무거운 쪽)."""
    digits = "".join(ch for ch in name if ch.isdigit())
    return int(digits) if digits else 0


def stage_bands(max_ma: float) -> list[dict]:
    """단계 하나하나를 띠로 — 그림의 왼쪽 MIS 기둥(209). `stage_ticks` 가
    경계(선)라면 이것은 그 사이(면)이고, 빙기(짝수)를 칠해 가른다.
    `max_ma` 가 LR04 끝(5.3 Ma)을 넘으면 거기까지만 낸다."""
    out = []
    prev_name, prev_ka = "1", 0.0
    for name, ka in BOUNDARIES_KA:
        top, base = prev_ka / 1000.0, ka / 1000.0
        if top >= max_ma:
            break
        out.append({"name": prev_name, "top_ma": top, "base_ma": min(base, max_ma),
                    "glacial": _stage_no(prev_name) % 2 == 0})
        prev_name, prev_ka = name.split("/")[1], ka
    return out
